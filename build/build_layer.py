#!/usr/bin/env python3
"""
build_layer.py — an instance's own DSL layer (its homebrew: NPCs, characters, house rules as
MODIFYs, lore) built as one more book, and gated as the books are.

    python3 build/build_layer.py <layer dir> --id campaign --label "Portents & Fortunes" --out campaign/data

An instance is a campaign repo forked from this VTT (PLAN.md, "Instances"); its layer lives in
its own folder and never in data/. This writes two files into --out:

  <id>.js    the layer's entities — a self-registering book file, loaded on demand like any book
  index.js   the layer's index record and its records, merged ahead of the corpus's at the `data`
             stage (engine/instance.js), so every list view leads with the layer

then gates them, and exits non-zero on any failure:

  1. COVERAGE and FIDELITY, by count — verify_data.py's rule over the layer's own files: every
     string the layer prints reaches its data as often as it is printed, and nothing in the
     data came from anywhere else.
  2. IDS — no entity of the layer takes an id the corpus uses.
  3. REFERENCES — every id the layer points at (the type a DEF EXTENDS, a LIST OF type, a
     reference, a MODIFY's target, any hash argument) is an entity of the layer or of the corpus.
     A homebrew NPC built on a mistyped chassis fails here, not at the table.
  4. NAMES — a reference with no hash (the corpus leaves some 2,000 entities unhashed, and names
     them bare where it points at them) must name an entity of the layer or the corpus: a MODIFY
     or OVERRIDE target, a CONCERNS entry, an item of a LIST OF a type. A name that matches none
     fails; a name that matches several is reported with the one the pages will resolve it to
     (the layer's own, then the core's — system/marvelmultiverse/data.js `named`).

The corpus side is read from data/*.js, so the books must be built first (build/build.sh).
"""
import argparse
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_data import (Build, Ctx, EXT_ORDER, HEADER_KWS, DSL_EXTS, LORE_EXTS, KINDS, first_page,  # noqa: E402
                        gen, lore_chapter, records_of)
from parse_dsl import parse_files  # noqa: E402
from verify_data import BLOB, TYPE_WORDS, data_strings, strings_of  # noqa: E402

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KIND = "campaign"
LAYER_BLOB = re.compile(r"var d=(\{.*\});var T=window\.MARVELMULTIVERSE", re.S)

BANNER = ("/* Generated by build/build_layer.py from this instance's DSL layer — do not edit by hand.\n"
          "   Every string is verbatim from the layer's files; regenerate rather than patch. */\n")
REGISTER = """(function(){var d=%s;var T=window.MARVELMULTIVERSE=window.MARVELMULTIVERSE||{books:{},entities:{},loaded:{}};
T.loaded[d.src]=true;T.books[d.book.id]=d.book;
for(var h in d.entities){T.entities[h]=d.entities[h];}})();
"""
# Merged into the corpus's index and records, FIRST — the shelf shelves the campaign first and every
# list view (NPCs, the Cast, techniques) leads with the campaign's own, not after 389 published NPCs
# and past a list's cut. Replaces its own earlier copy, so a reload is a no-op.
INDEX = """(function(){var d=%s;var T=window.MARVELMULTIVERSE=window.MARVELMULTIVERSE||{books:{},entities:{},loaded:{}};
var I=T.index=T.index||{books:[],counts:{}};I.counts=I.counts||{};
var had=(I.books||[]).some(function(b){return b.id===d.book.id;});
I.books=(I.books||[]).filter(function(b){return b.id!==d.book.id;});I.books.unshift(d.book);
if(!had){I.counts.books=(I.counts.books||0)+1;I.counts.entities=(I.counts.entities||0)+d.book.counts.entities;
I.counts.files=(I.counts.files||0)+d.book.counts.chapters;I.counts.records=(I.counts.records||0)+d.records.length;}
T.records=d.records.concat((T.records||[]).filter(function(r){return r.book!==d.book.id;}));})();
"""


def layer_files(root):
    out = []
    for dirpath, _dirs, files in os.walk(root):
        for fn in files:
            if fn.endswith(DSL_EXTS + LORE_EXTS) and not fn.startswith("."):
                out.append(os.path.relpath(os.path.join(dirpath, fn), root))
    return sorted(out)


def corpus_entities():
    """Every entity the built books carry (data/*.js): id → (name, book, form), for the ids,
    references and names gates."""
    ents = {}
    data_dir = os.path.join(HERE, "data")
    for fn in sorted(os.listdir(data_dir)):
        if not fn.endswith(".js"):
            continue
        m = BLOB.search(open(os.path.join(data_dir, fn), encoding="utf-8").read())
        if m:
            for h, e in json.loads(m.group(1))["entities"].items():
                ents[h] = (e.get("name"), e.get("book"), e.get("form"))
    if not ents:
        raise SystemExit("build_layer: no book data in data/ — run build/build.sh first")
    return ents


def named_refs(book):
    """Every reference the layer makes by name alone: (where, name)."""
    out = []

    def blocks(lst, where):
        for b in lst or []:
            if not isinstance(b, dict):
                continue
            args = b.get("args") or []
            if b.get("kw") in ("MODIFY", "OVERRIDE") and not any("h" in a for a in args):
                out.extend([(b["kw"] + " target", a["c"]) for a in args if "c" in a][:1])
            if b.get("kw") == "CONCERNS" and args and "l" in args[0]:
                out.extend(("CONCERNS in " + where, a["c"]) for a in args[0]["l"] if "c" in a and "h" not in a)
            blocks(b.get("body"), where)

    for c in book["book"]["chapters"]:
        blocks(c.get("blocks"), c["file"])
    for h, e in book["entities"].items():
        for p in e.get("props", []):
            if p.get("vk") == "list" and p.get("ofHash"):
                out += [("%s in %s" % (p["name"], e["name"]), a["c"]) for a in p.get("items", []) if "c" in a and "h" not in a]
        blocks(e.get("blocks"), e["name"])
    return out


def pointed_at(node, out):
    """Every id a layer entity points at: typeHash, ofHash, a reference's hash, a hash argument."""
    if isinstance(node, dict):
        for k, v in node.items():
            if k in ("typeHash", "ofHash", "hash", "h") and isinstance(v, str):
                out.add(v)
            else:
                pointed_at(v, out)
    elif isinstance(node, list):
        for x in node:
            pointed_at(x, out)
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("layer", help="the instance's DSL layer folder")
    ap.add_argument("--id", required=True, help="the layer's book id (e.g. campaign)")
    ap.add_argument("--label", required=True, help="the layer's title on the shelf")
    ap.add_argument("--out", required=True, help="where the two files go, relative to the site root")
    a = ap.parse_args()

    root = os.path.abspath(a.layer)
    rels = layer_files(root)
    if not rels:
        raise SystemExit("build_layer: no DSL or .lore files under %s" % a.layer)
    out_dir = os.path.abspath(a.out)
    os.makedirs(out_dir, exist_ok=True)
    book_path = os.path.join(out_dir, "%s.js" % a.id)
    src = os.path.relpath(book_path, HERE).replace(os.sep, "/")
    if src.startswith(".."):
        print("build_layer: note — %s lies outside the site, so no page can load it (fine for a test build)" % a.out)

    # ── build: one book, by build_data.py's own walk ─────────────────
    build = Build()
    chapters = []
    for rel in rels:
        path = os.path.join(root, rel)
        ext = os.path.splitext(rel)[1]
        chapters.append(lore_chapter(path, rel) if ext in LORE_EXTS
                        else {"file": rel, "kind": ext[1:], "page": first_page(path), "_path": path})
    chapters.sort(key=lambda c: (EXT_ORDER.get(os.path.splitext(c["file"])[1], 9), c["file"]))
    roots = []
    for c in chapters:
        if c["kind"] == "lore":
            continue
        doc = parse_files([c.pop("_path")])[0]
        c["container"], c["module"] = doc["container"], doc["name"]
        if doc.get("extends"):
            c["moduleExtends"] = doc["extends"]
        ctx = Ctx(build, doc, a.id, None, None)
        before = set(build.entities)
        c["blocks"] = []
        for x in doc["body"]:
            if x.get("n") == "kw" and x["kw"] in HEADER_KWS:
                continue
            if x.get("n") == "kw" and x["kw"] == "NAME" and "name" not in c and len(x["args"]) == 1 and x["args"][0]["k"] == "str" and x.get("body") is None:
                c["name"] = x["args"][0]["v"]
                continue
            c["blocks"].append(gen(x, ctx))
        c["roots"] = [h for h in build.entities if h not in before and build.entities[h]["parent"] is None]
        roots.extend(c["roots"])

    entities = build.entities
    records = records_of(entities)
    rec = {"id": a.id, "label": a.label, "kind": KIND, "chapters": chapters, "entities": roots}
    with open(book_path, "w", encoding="utf-8") as fh:
        fh.write(BANNER)
        fh.write(REGISTER % json.dumps({"src": src, "book": rec, "entities": entities}, ensure_ascii=False, sort_keys=True))
    by_ext = {}
    for c in chapters:
        by_ext[c["kind"]] = by_ext.get(c["kind"], 0) + 1
    index_rec = {
        "id": a.id, "label": a.label, "kind": KIND, "files": {"main": [src]},
        "chapters": [{"file": c["file"], "kind": c["kind"], "name": c.get("name"), "page": c["page"]} for c in chapters],
        "counts": {"entities": len(entities), "chapters": len(chapters), "files": by_ext},
        "bytes": os.path.getsize(book_path),
    }
    with open(os.path.join(out_dir, "index.js"), "w", encoding="utf-8") as fh:
        fh.write(BANNER)
        fh.write(INDEX % json.dumps({"book": index_rec, "records": records}, ensure_ascii=False, sort_keys=True))
    print("build_layer: %d files → %s/%s.js (%d entities, %d records) and index.js"
          % (len(rels), a.out, a.id, len(entities), len(records)))

    # ── gates, read back from the files as written ───────────────────
    fail = 0
    want, skipped = strings_of(root, rels)
    book_blob = json.loads(LAYER_BLOB.search(open(book_path, encoding="utf-8").read()).group(1))
    index_blob = json.loads(LAYER_BLOB.search(open(os.path.join(out_dir, "index.js"), encoding="utf-8").read()).group(1))
    in_book = data_strings([book_blob])
    everywhere = in_book + data_strings([index_blob])
    ours = set(TYPE_WORDS) | KINDS | {KIND, a.label, src}
    missing = sorted(k for k in want if k not in in_book)
    short = sorted(k for k in want if k in in_book and in_book[k] < want[k])
    unsourced = sorted(k for k in everywhere if k not in want and k not in ours and k not in skipped)
    for label, rows in (("UNCOVERED — in the layer, not in its data", missing),
                        ("SHORT — printed more often than the data carries it", short),
                        ("UNSOURCED — in the data, not in the layer", unsourced)):
        if rows:
            fail = 1
            print("  %s: %d" % (label, len(rows)))
            for s in rows[:25]:
                print("    %r" % s[:130])
    if not (missing or short or unsourced):
        print("  strings: %d (%d occurrences) — 0 uncovered · 0 short · 0 unsourced" % (len(want), sum(want.values())))

    corpus_all = corpus_entities()
    corpus = set(corpus_all)
    taken = sorted(set(entities) & corpus)
    if taken:
        fail = 1
        print("  IDS — the layer reuses %d corpus ids: %s" % (len(taken), ", ".join(taken[:10])))
    else:
        print("  ids: %d, none of them the corpus's (%d)" % (len(entities), len(corpus)))
    dangling = sorted(pointed_at(entities, set()) - set(entities) - corpus)
    if dangling:
        fail = 1
        print("  REFERENCES — %d ids the layer points at are in neither the layer nor the corpus: %s"
              % (len(dangling), ", ".join(dangling[:10])))
    else:
        print("  references: every id the layer points at resolves (layer or corpus)")
    by_name = {}
    for h, (nm, bk, form) in corpus_all.items():
        by_name.setdefault(nm, []).append((h, bk, form))
    for h, e in entities.items():
        by_name.setdefault(e["name"], []).append((h, a.id, e.get("form")))
    refs = named_refs(book_blob)
    unknown = [(w, nm) for w, nm in refs if nm not in by_name]
    if unknown:
        fail = 1
        print("  NAMES — %d references name nothing in the layer or the corpus:" % len(unknown))
        for w, nm in unknown[:25]:
            print("    %r (%s)" % (nm, w))
    else:
        print("  names: %d references by name, every one names an entity" % len(refs))
    for w, nm in sorted(set(refs)):
        hits = [x for x in by_name.get(nm, []) if x[2] != "ENTITY"] or by_name.get(nm, [])
        if len(hits) > 1:
            pick = (next((x for x in hits if x[1] == a.id), None) or next((x for x in hits if x[1] == "core"), None) or hits[0])
            print("    note — %r (%s) names %d entities; the pages resolve it to %s in %s" % (nm, w, len(hits), pick[0], pick[1]))
    print("build_layer: %s" % ("FAILED" if fail else "OK"))
    return fail


if __name__ == "__main__":
    sys.exit(main())
