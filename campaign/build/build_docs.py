#!/usr/bin/env python3
"""
build_docs.py — campaign/docs/*.md → campaign/data/docs.js (window.XFRONT_DOCS), the public pages'
own prose. The heroes' pages are drawn at runtime from the layer's profiles (campaign/site/site.js);
this carries only what is written as prose.

    python3 campaign/build/build_docs.py

Markdown kept small on purpose: front matter (title, subtitle), paragraphs, *emphasis*.

Gates (exit non-zero):
  * NAMES — every capitalised word that does not begin a sentence is on a hero's sheet
    (campaign/source/sheets/*.txt) or in ALLOWED: a public page says nothing the sheets don't.
  * WORDS — the page's words, read back from docs.js with its markup stripped, are the source's.
"""
import html
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DOCS = os.path.join(ROOT, "campaign", "docs")
OUT = os.path.join(ROOT, "campaign", "data", "docs.js")
SHEETS = os.path.join(ROOT, "campaign", "source", "sheets")
ALLOWED = {"Marvel", "Multiverse"}   # the game's name, in the subtitle


def read(path):
    s = open(path, encoding="utf-8").read()
    m = re.match(r"^---\n(.*?)\n---\n", s, re.S)
    meta = dict(ln.split(": ", 1) for ln in m.group(1).splitlines())
    body = s[m.end():].strip()
    paras = [re.sub(r"\s*\n\s*", " ", p).strip() for p in re.split(r"\n\s*\n", body) if p.strip()]
    return meta, paras


def inline(p):
    return re.sub(r"\*([^*]+)\*", r"<em>\1</em>", html.escape(p, quote=False))


def main():
    fail = 0
    sheet_text = " ".join(open(os.path.join(SHEETS, f), encoding="utf-8").read() for f in os.listdir(SHEETS) if f.endswith(".txt"))
    stem = lambda w: re.sub(r"[’']s?$", "", w)  # noqa: E731 — "Xavier’s" is Xavier
    sheet_words = {stem(w) for w in re.findall(r"[A-Za-z][\w’'-]*", sheet_text)}
    out = {}
    for fn in sorted(os.listdir(DOCS)):
        if not fn.endswith(".md"):
            continue
        meta, paras = read(os.path.join(DOCS, fn))
        for p in [meta.get("subtitle", "")] + paras:
            for m in re.finditer(r"(?<![.!?:]\s)(?<!^)\b([A-Z][\w’'-]+)", p):
                w = stem(m.group(1))
                if w not in sheet_words and w not in ALLOWED:
                    print("  NAMES — %s: %r is on no hero's sheet" % (fn, m.group(1)))
                    fail = 1
        out[fn[:-3]] = {"title": meta["title"], "subtitle": meta.get("subtitle", ""), "html": "".join("<p>%s</p>" % inline(p) for p in paras)}
        back = re.sub(r"<[^>]+>", " ", out[fn[:-3]]["html"])
        if html.unescape(back).split() != " ".join(re.sub(r"\*", "", p) for p in paras).split():
            print("  WORDS — %s: the page's words differ from the source's" % fn)
            fail = 1
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("/* Generated by campaign/build/build_docs.py from campaign/docs/ — do not edit by hand. */\n")
        fh.write("window.XFRONT_DOCS = %s;\n" % json.dumps(out, ensure_ascii=False, sort_keys=True))
    print("build_docs: %d pages → campaign/data/docs.js" % len(out))
    print("build_docs: %s" % ("FAILED" if fail else "OK"))
    return fail


if __name__ == "__main__":
    sys.exit(main())
